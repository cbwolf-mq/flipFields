def symIsPoly(p,v,D,relaxed=True):
  """
  Checks if a polynomial string is well-formed, i.e.
  - each term starts with a number
  - all other factors in this term are a variable from v
  - the term closes with "*"
  
  Parameters
  ----------
  p : str
    Polynomial.
  v : set of str
    variables. If v is the empty set, skip the variable test.
  D : int
    Modulus of the flipField.
  relaxed : bool
    Skip check if all factors are elements of the flipInts, i.e. if relaxed=True, also even numbers are allowed as factors.  

  Returns
  -------
  bool
    True iff p is well-formed regarding v, D and relaxed
  """
  assert isField(D), "no field for D=%d"%D
  
  # empty string is not allowed
  if p == "": return False
  
  # check if the input is valid
  if p[-1] != "*": return False
    
  # split by terms
  terms = p.split("+")  
  for t in terms:
    facs = t.split("*")
    if facs[-1] != "": return False
    if not(facs[0].isdigit()): return False
    if not(relaxed) and not(isElem(int(facs[0]),D)): return False
    for f in facs[1:-1]:
      if not(f in v) and len(v) > 0: return False
  return True 


def symPolyIsOdd(p,D):
  """
  Returns if the sum of the factors of the polynomial are odd.
  Assuming all input variables are odd, the output will be odd, too.

  Parameters
  ----------
  p : str
    Polynomial as a string.
  D : int
    Generator of the flipInts.

  Returns
  -------
  bool
    True iff the sum of the factors is odd.
  """
  assert isField(D), "no field for D=%d"%D
  
  # check if the input is valid
  if p[-1] != "*": return False
    
  # split by terms, get the factors
  terms = p.split("+") 
  sumFac = 0
  for t in terms:
    facs = t.split("*")
    if facs[-1] != "": return False
    if not(facs[0].isdigit()): return False
    sumFac += int(facs[0])
  return (sumFac % 2) == 1


def symIsLinear(p,v,D):
  """
  Verifies if p is a valid polynomial and also of degree 1.

  Parameters
  ----------
  p : str
    Polynomial.
  v : set of str
    variables.
  D : int
    Modulus of the flipField.

  Returns
  -------
  bool
    True iff the input polynomial is linear.
  """
  assert symIsPoly(p,v,D), "Not a polynomial with "+p
  return functools.reduce(lambda a,b: a and b, [ s.count("*") == 2 for s in p.split("+") ] )


def symIsAffine(p,v,D):
  """
  Verifies if p is a valid polynomial and also of degree 1 or 0.

  Parameters
  ----------
  p : str
    Polynomial.
  v : set of str
    variables.
  D : int
    Modulus of the flipField.

  Returns
  -------
  bool
    True iff the input polynomial is affine.
  """
  assert symIsPoly(p,v,D), "Not a polynomial with "+p
  if symIsLinear(p,v,D): return True
  return functools.reduce(lambda a,b: a and b, [ s.count("*") == 1 for s in p.split("+") ] )


def symIsPolyInt(p,D):
  """
  Checks if the input is actually a number, e.g. '0*' or '5*'

  Parameters
  ----------
  p : str
    Symbolic polynomial.
  D : int
    Modul that generates the corresponding FlipInts.

  Returns
  -------
  bool
    True iff p is a number, not a proper polynomial.
  """
  assert isField(D), "Wrong D with {}".format(D)
  assert symIsPoly(p,set(),D), "Not a poly with {}".format(p)
  # how many terms?
  if p == "": return True
  if p.count("+") > 0: return False
  if p.count("*") != 1: return False
  f = p.split("*")
  if not(f[0].isdigit()): return False
  return True


def symPoly2int(p,D):
  """
  For polynomials of the form 'a*' and 'a' a natural number, return int('a').

  Parameters
  ----------
  p : str
    polynomial.
  D : int
    Integer generating the current FlipInts.

  Returns
  -------
  int
    Natural number.
  """
  assert isField(D), "Wrong D with {}".format(D)
  assert symIsPolyInt(p,D), "Non-polynomial with {}".format(p)
  if p == "": return 0
  f = p.split("*")
  return int(f[0])


def symAllVars(inEq,D):
  """
  Returns all variables for a given equation.

  Parameters
  ----------
  inEq : str
    Equation.

  Returns
  -------
  set
    set of all variables in this equation.
  """
  outSet = set()
  if inEq == "": return outSet
  for t in inEq.split("+"):
    for f in t.split("*"):
      if (len(f) > 0) and not(f.isdigit()): outSet.add(f)
  assert symIsPoly(inEq,outSet,D), "Wrong equation for >>>"+inEq+"<<<"
  return outSet    


def symSetEqs(eqs,v,var2val,D):
  """
  For a given list of equations, replace one variable by an integer value.

  Parameters
  ----------
  eqs : list
    Equations as list of strings.
  v : set
    set of variables (as strings).
  var2val : dict
    variable to a definite value.
  D : int
    fieldInt.

  Returns
  -------
  list
    list of strings. Equations after replacing a variable.
  """
  # check if each equation is well-formed
  for eq in eqs:
    assert symIsPoly(eq,v,D), "Problem Eq  " + eq 
  assert (len(var2val.keys())) == 1, "Too many variables with " +str(var2val) 
  curKey = list(var2val.keys())[0]
  curVar = var2val[curKey]
  assert str(curVar).isdigit(), "Non-digit value for "+str(var2val)+" and !%s!"%(curVar)
  targetVar = "*" + str(curKey) + "*"
  # if applicable, replace each variable in var2val by its value
  for i in range(len(eqs)):
    pos = eqs[i].find(targetVar)
    if pos < 0: continue
    # split the equation
    terms = eqs[i].split("+")
    outList = []
    for t in terms:
      pos = t.find(targetVar)
      if pos < 0: 
        outList.append(t)
        continue
      t = t.replace(targetVar,"*")
      # only get the constant term
      monConst = t.split("*",1)
      assert monConst[0].isdigit()
      fac = int(monConst[0]) * var2val[curKey] % D
      # make sure we have a non-zero term
      if fac == 0: continue
      outStr = str(fac) + "*"
      outStr += monConst[1]
      outList.append(outStr)
    eqs[i] = symAddUp("+".join(outList),D)
  # check the output
  for i in range(len(eqs)):
    eq = eqs[i]
    if eq == "": eqs[i] = "0*"; continue
    assert symIsPoly(eq,v,D), "Problem Eq 2: >{}< at {}".format(eq,i)
  return eqs    


def symSetEqsPoly(eqs,v,var2poly,D):
  """
  Replaces a given variable by a polynomial. Multiplies out and collects terms in the process.
  The result is a valid polynomial in the given set of variables.

  Parameters
  ----------
  eqs : list
    List of str, each of them is a valid polynomial.
  v : set
    Set of variables that form the polynomial.
  var2poly : dict
    New polynomial for a variable. Only one variable is allowed, i.e. the dictionary only has one key.
  D : int
    Generating integer for the corresponding flipInts.

  Returns
  -------
  TYPE
    DESCRIPTION.
  """
  assert isField(D), "Wrong flipInts with "+str(D)
  for eq in eqs:
    assert symIsPoly(eq,v,D), "Problem Eq  " + eq 
  assert (len(var2poly.keys())) == 1, "Too many variables with " +str(var2poly) 
  curKey = list(var2poly.keys())[0]
  curVar = var2poly[curKey]
  
  assert (var2poly[curKey] == "") or (symIsPoly(var2poly[curKey],v,D)), "Non polynomial value for "+str(var2poly)+" and !%s!"%(curVar)+" and v="+str(v)
  targetVar = "*" + str(curKey) + "*"  
  newTerms = var2poly[curKey].split("+")
  if var2poly[curKey] == "": newTerms = ["0*"]
  for i in range(len(eqs)):
    pos = eqs[i].find(targetVar)
    if pos < 0: continue
    # split the equation
    terms = eqs[i].split("+")
    outList = []
    for t in terms:
      pos = t.find(targetVar)
      if pos < 0: 
        outList.append(t)
        continue
      for newTerm in newTerms:
        newT = t.replace(targetVar,"*"+newTerm)
        newT = symSortTerms(newT, v, D)
        if newT != "0*": outList.append(newT)
    newEq = "+".join(outList)  
    eqs[i] = symAddUp(newEq,D)
  while "" in eqs: eqs.remove("")
  # check the output
  for eq in eqs:
    assert symIsPoly(eq,v,D,relaxed=True), "Problem Eq 2: " + eq   
  return eqs    


def symSortTerms(inEq,v,D):
  """
  For a given polynomial, sorts all terms and also multiplies out factors.

  Parameters
  ----------
  inEq : str
    Input polynomial.
  v : set
    Set of all variables in the input polynomial, may be set([]).
  D : int
    Number generating the corresponding flipInts.

  Returns
  -------
  str
    Sorted and multiplied polynomial.
  """
  assert isField(D), "Invalid flipInts with "+str(D)
  outEq = ""
  for t in inEq.split("+"):
    allVars = t.split("*")
    allVars.remove("")
    f = 1
    for a in allVars:
      if not(a.isdigit()): continue
      f *= int(a)
    f %= D  
    allVars = filter(lambda a: not(a.isdigit()),allVars)
    allVars = sorted(allVars)  
    if outEq != "": outEq += "+"
    outEq += str(f)+"*"+"*".join(allVars)
    if len(allVars) > 0: outEq += "*"
  return outEq  


def symPolyMult(leftPrefix, leftCnt, rightPrefix, rightCnt, D):
  """
  Multiply two polynomials in a given number of variables each.

  Parameters
  ----------
  leftPrefix : str
    Variable of the left factor
  leftCnt : int
    Maximal degree of the left polynomial.
  rightPrefix : str
    Variable of the right factor.
  rightCnt : int
    Maximal degree of the right polynomial.
  D : int
    Generating number for the flipInt  

  Returns
  -------
  list
    List of strings, result of this multiplication.
  """
  outList = []
  for k in range(leftCnt+rightCnt-1):
    outList.append("")
  for i in range(leftCnt):
    for j in range(rightCnt):
      if outList[i+j] != "": outList[i+j] += "+"
      outList[i+j] += "1*" + leftPrefix + str(i) + "*" + rightPrefix + str(j) + "*"
  v = set([leftPrefix + str(i) for i in range(leftCnt)] + [rightPrefix + str(j) for j in range(rightCnt)])    
  for curEq in outList:    
    assert symIsPoly(curEq,v,D), "Problem Eq  " + curEq 
  return outList


def symMultPolyPoly(left, right, D):
  """
  Symbolic multiplication of two polynomials.

  Parameters
  ----------
  left : str
    Polynomial.
  right : str
    Polynomial.
  D : int
    generating number for the flipInt.

  Returns
  -------
  str
    (left * right) % D. All terms are alphabetically sorted and added up.
  """
  assert isField(D), "Invalid flipInts with "+str(D)
  v = symAllVars(left,D).union(symAllVars(right,D))
  assert symIsPoly(left,v,D), "Problem left >>>" + left + "<<<"
  assert symIsPoly(right,v,D), "Problem right >>>" + right + "<<<"
  leftTerms = left.split("+")
  rightTerms= right.split("+")
  # multiply term by term
  resTerms = ""
  for l in leftTerms:
    facLeft,l = l.split("*",1)
    for r in rightTerms:
      facRight,r = r.split("*",1)
      fac = (int(facLeft) * int(facRight)) % D
      tmpTerm = str(fac) + "*" + l + r
      # collect and rewrite
      resTerms = resTerms + "+" + tmpTerm if resTerms != "" else tmpTerm
  resTerms = symSortTerms(resTerms,v,D)
  resTerms = symAddUp(resTerms,D)
  if resTerms == "": resTerms = "0*"
  return resTerms    


def symMultMatVec(inMat,inVec,D,relaxed=False):
  """
  Symbolic computation of "Ab" for A a matrix and b a vector over flipInts.

  Parameters
  ----------
  inMat : list
    List of list of str. Matrix A.
  inVec : list
    List of str. Vector b.
  D : int
    Generates the corresponding FlipInts.
  relaxed : bool, optional
    Skips the check if all elements are from the correspondig FlipInts. The default is False.

  Returns
  -------
  list
    Result of the matrix-vector-multiplication "Ab".
  """
  assert isField(D), "Wrong D with "+str(D)
  # check that the matrix is rectantular and the correct size for inVec
  i = len(inVec)
  for j in range(len(inMat)): 
    assert len(inMat[j]) == i, "matrix inMat[j] with j={} different from i={}".format(j,i)
  # extract variables    
  allVars = set()
  for c in inVec:
    s = symAllVars(c,D)
    allVars.update(s)
  for i in range(len(inVec)):
    for j in range(len(inMat)):
      s = symAllVars(inMat[i][j],D)
      allVars.update(s)
  # check if input are valid equations
  for c in inVec:
    assert symIsPoly(c,allVars,D,relaxed), "Wrong eq with c={} and D={}".format(c,D)  
  for i in range(len(inVec)):
    for j in range(len(inMat)):
      assert symIsPoly(inMat[i][j],allVars,D,relaxed), "Wrong eq with i={}, j={}, inMat[i][j]={} and D={}".format(i,j,inMat[i][j],D)  
  #  multiply each element in the matrix with the corresponding element in the vector
  outVec = []
  for j in range(len(inMat)):
    outPoly = "+".join(symMultPolyPoly(inVec[i],inMat[j][i],D) for i in range(len(inVec)))
    outPoly = symAddUp(outPoly,D)
    outVec.append(outPoly)
  return outVec


def symMultMatMat(A,B,D):
  """
  Computes the product A x B for A,B two matrices.

  Parameters
  ----------
  A : list
    (l x m)-matrix, list of lists.
  B : list
    (m x n)-matrix, list of lists.
  D : int
    Generates the corresponding FlipInts.

  Returns
  -------
  list
    (l x n)-matrix, product of A and B.
  """
  l = len(A)
  m = len(B)
  assert (m == len(A[0]))
  n = len(B[0])
  # create the result
  R = []
  for i in range(l):
    R.append([""] * n)
  # multiply  
  for i in range(l):
    for k in range(n):
      tmp = "+".join([ symMultPolyPoly(A[i][j],B[j][k],D) for j in range(m) ])
      tmp = symSortTerms(tmp,set(),D)
      R[i][k] = symAddUp(tmp,D)
  return R
   

def symSubtractTerm(eqStr, subStr, D):
  """
  Subtract subStr from the current equation.

  Parameters
  ----------
  eqStr : str
    Polynomial for the current equation.
  subStr : str
    Term to be subtracted.
  D : int
    Current FlipInts.

  Returns
  -------
  str
    New polynomial.
  """
  subSplit = subStr.split('*',1)
  subFac = int(subSplit[0]); subTerm = subSplit[1]
  allTerms = eqStr.split('+')
  outEq = ""
  isIn = False
  termList = []
  for curTerm in allTerms:
    if curTerm == "": continue
    fullSplit = curTerm.split('*',1)
    fac = int(fullSplit[0]); term = fullSplit[1]
    if subTerm == term:
      isIn = True
      newFac = (D + fac - subFac) % D
      if newFac != 0: termList.append(str(newFac) + "*" + subTerm)
    else: termList.append(curTerm)
  if isIn == False: 
    newFac = (D - subFac) % D; 
    if outEq != "": outEq += "+"
    termList.append(str(newFac) + "*" + subTerm)
  outEq = "+".join(termList)  
  return outEq
  

def symAddUp(inEq,D):
  """
  Adds up all terms that share the same variables. Assumes all terms are well-ordered.

  Parameters
  ----------
  inEq : str
    input equation.
  D : int
    Generating number for the flipInts.

  Returns
  -------
  set
    Output equation.
  """
  v = symAllVars(inEq, D)
  if inEq == "": return ""
  assert symIsPoly(inEq,v,D), "Problem In Eq " + inEq 
  outDict = {}
  for t in inEq.split("+"):
    fac,allVars = t.split("*",1)
    if not(allVars in outDict): outDict[allVars] = 0
    outDict[allVars] = (outDict[allVars] + int(fac)) % D
  # delete zero equations
  for curVar in list(outDict.keys()):
    if outDict[curVar] == 0: del outDict[curVar]
  # generate output
  outEq = "+".join([ str(outDict[v])+"*"+v for v in sorted(outDict.keys()) ])
  # delete 0 terms
  if outEq == "": outEq = "0*"
  assert symIsPoly(inEq,v,D), "Problem Out Eq " + outEq 
  return outEq


def symMultFacPoly(f,p,v,D):
  """
  Multiplies a given polynomial p by an integer factor f. 

  Parameters
  ----------
  f : int
    Factor.
  p : str
    Polynomial.
  v : set
    Set of all variables.
  D : int
    Modul generating the flipInts.

  Returns
  -------
  str
    Polynomial.
  """
  assert symIsPoly(p,v,D), "Problem Eq " + p
  assert isElem(f, D)
  outStr = ""
  for t in p.split("+"):
    fac,rest = t.split("*",1)
    fac = (int(fac)*f) % D
    if outStr != "": outStr += "+"
    outStr += str(fac) + "*" + rest
  return outStr  
  

def symRewriteEqsLin(leftPrefix, leftCnt, rightPrefix, rightCnt, rightSet, D):
  """
  Removes all closed equations, i.e. equations that have coefficients that add up to an even number.
  All remaining equations are active, i.e. their coefficients add up to an odd number. These produce odd output.

  Parameters
  ----------
  leftPrefix : str
    Prefix for the variables in the polynomial in the left term.
  leftCnt : int
    Number of variables for the left term in the polynomial.
  rightPrefix : str
    Prefix for the variables in the polynomial in the right term.
  rightCnt : int
    Number of variables for the right term in the polynomial.
  rightSet : dict
    Dictionary for the variable in the right factor that are set in the result.
  D : int
    Generating number for the flipInts.

  Returns
  -------
  eqs : list
    Equations in form of polynomials. The output variable is implicit.
  fullReplace : dict
    Variables that have been replaced by polynomials.
  """
  assert isinstance(rightSet,dict), "No dict for "+str(rightSet)
  # generate the system of equations by multiplying left and right variables
  eqs = symPolyMult(leftPrefix, leftCnt, rightPrefix, rightCnt, D)
  # assign random values to the rhs
  allVars = set([ leftPrefix + str(i) for i in range(leftCnt) ] + [ rightPrefix + str(j) for j in range(rightCnt)])
  fullReplace = {}
  for curVar in [ rightPrefix + str(j) for j in range(rightCnt)]:
    assert curVar in rightSet, "Variable does not exist in rightSet for "+curVar
    eqs = symSetEqs(eqs, allVars, {curVar: rightSet[curVar]} , D)
  
  # simplify the system, eliminate closed equations
  done = False
  while (not done):
    done = True
    # check if some polynomial has only one variable - this means the variable is zero
    # check if we have closed equations
    while len(eqs) != 0:
      # check if all equations are linear
      for j in range(len(eqs)): 
        assert symIsAffine(eqs[j],allVars,D), "Non-affine equation for "+eqs[j]
      # find a closed equation with minimal number of terms  
      i = -1; foundEq = -1; foundCnt = 10**100; foundLen = 10**100
      while True:
        i += 1    
        if i >= len(eqs): break
        if symPolyIsOdd(eqs[i-1],D): continue # active equation
        
        eqLen = len(eqs[i])
        cnt = eqs[i-1].count("+")
        if (cnt < foundCnt) or ((cnt == foundCnt) and (eqLen < foundLen)): foundCnt = cnt; foundEq = i-1; foundLen = eqLen  
      if foundEq == -1: break  # no closed equation      
      # remove one variable, make sure leading term is 1
      if eqs[foundEq].count("+") >= 1: t,r = eqs[foundEq].split("+",1)
      else: t = eqs[foundEq]; r = ""
      
      f,v = t.split("*",1)
      assert f.isdigit(), "Wrong number with "+f
      
      f = int(f); 
      if (f % 2) == 1:
        f = (D -f) % D; f = invMul(f, D)
      else:
        # we have an even factor here---split into two odd factors
        r += ("" if r=="" else "+") + (str((f-1) % D))+"*"+v
        f = 1
      repVar = v.replace("*","")
      if r != "": r = symMultFacPoly(f, r, allVars, D)
      fullReplace[repVar] = r
      # remove var/Eqs
      del eqs[foundEq]
      # set the variable accordingly
      eqs = symSetEqsPoly(eqs,allVars,{repVar: fullReplace[repVar]},D)
              
      done = False
    return eqs,fullReplace


def symIsSol(eqs,sol,D):
  """
  Checks if the input actually solves the system of equations.
  Copies variables eqs into a new list.

  Parameters
  ----------
  eqs : list
    System of equations, list of str.
  sol : dict
    Possible solution for the sytem of equstions eqs.
  D : int
    Generating number for the FlipInts.

  Returns
  -------
  bool
    True iff this is a valid solution.
  """
  assert isField(D), "Wrong D with "+str(D)
  # extract variables
  allVars = set()
  for e in eqs:
    s = symAllVars(e,D)
    allVars.update(s)
  for r in sol:
    s = symAllVars(sol[r],D)
    allVars.update(s)
  # check if input are valid equations
  for e in eqs:
    assert symIsPoly(e,allVars,D,relaxed=True), "Wrong eq with {} and D={}".format(e,D)  
  # apply the solution, make a deep copy
  eqs = deepcopy(eqs)
  for v in sol:
    eqs = symSetEqsPoly(eqs,allVars,{v: sol[v]},D)
  # check result
  outRes = True
  for e in eqs:
    if e != "0*": outRes = False
  return outRes


def symSolveLinSys(eqs,D):
  """
  Solves a linear system of equations and returns the result as a dict of variables and values.

  Parameters
  ----------
  eqs : list
    Final equations after the solving.
  D : int
    Integer generating the corresponding FlipInts.

  Returns
  -------
  eqs : list
    Equations after the solving, should be [].
  repDict : dict
    All variables in a dictionary with their corresponding value, e.g. {'a': '9*'}.
  """
  assert isField(D), "Wrong D with "+str(D)
  allVars = set()
  for e in eqs:
    s = symAllVars(e,D)
    # print("s={}".format(s))
    allVars.update(s)
  
  # print("Got all Vars "+str(allVars))
  for e in eqs:
    # print("Input {}".format(e))
    assert symIsPoly(e,allVars,D,relaxed=True), "Wrong eq with {} and D={}".format(e,D)
  
  # save them for later
  inEqs = deepcopy(eqs)
  
  # simplify the system, eliminate closed equations
  repDict = {}
  done = False
  while (not done):
    done = True
    # check if some polynomial has only one variable - this means the variable is zero
    # check if we have closed equations
    while len(eqs) != 0:
      # divide each line by the gcd of this line
      for i in range(len(eqs)):
        fullGCD = functools.reduce(math.gcd, [ int(e.split("*",1)[0]) if e != "0*" else 2*3*5*7*11*13*17*17 for e in eqs[i].split("+") ])
        if (fullGCD == 1) or (fullGCD == 0): continue
        # divide the whole line by this gcd
        termList = []
        for t in eqs[i].split("+"):
          f,r = t.split("*",1)
          f = int(f)
          assert (f % fullGCD) == 0, "Not divisible by gcd with num={}, gcd={}".format(f,fullGCD)
          f //= fullGCD
          termList.append(str("*".join([str(f),r])))
        eqs[i] = "+".join(termList)  
        
      # find a closed equation with minimal number of terms  
      # one factor for a variable must be odd
      i = -1; foundEq = -1; foundTerms = 10**100; foundLen = 10**100
      while True:
        i += 1    
        if i >= len(eqs): break
        
        # check if we have an odd variable in the equation
        for t in eqs[i].split("+"):
          # make sure we have a variable
          if t.count("*") != 2: continue
          f,v,r = t.split("*")
          if (int(f) % 2) == 0: continue
          tmpTerm = t
          # check if this equation is shorter
          eqLen = len(eqs[i])
          terms = eqs[i].count("+")
          # print("#terms "+str(terms))
          # take the shortest equation measured in #terms
          if (terms < foundTerms) or ((terms == foundTerms) and (eqLen < foundLen)): 
            foundEq = i; foundTerm = tmpTerm; foundTerms = terms; foundLen = eqLen  
            # print("found v={}, #={} and len={}".format(foundTerm,foundEq,foundLen))
      if foundEq == -1: break  # no closed equation      
      # print("found eq num {} with eq: {}".format(foundEq,eqs[foundEq]))
      # remove one variable, make sure leading term is 1
      if eqs[foundEq].count("+") >= 1: t,r = eqs[foundEq].split("+",1)
      else: t = eqs[foundEq]; r = ""
      
      # print("all eqs")
      # for i in range(len(eqs)):
      #   print("  {}: {}".format(i,eqs[i]))
      
      # remove term from the current equation
      workingEq = symSubtractTerm(eqs[foundEq], foundTerm, D)
      f,v,r = foundTerm.split("*")
      assert f.isdigit(), "Wrong number with "+f
      f = int(f); 
      assert (f % 2) == 1, "Wrong factor for "+str(f)
      assert r == "", "Wrong rest for "+r            
      f = (D -f) % D; f = invMul(f, D)
      if workingEq != "": workingEq = symMultFacPoly(f, workingEq, allVars, D)
      # print("newWorkingEquation "+workingEq)
      repDict[v] = workingEq
      # remove var/Eqs
      del eqs[foundEq]
      # set the variable accordingly
      # print("rep "+str({v: repDict[v]}))
      eqs = symSetEqsPoly(eqs,allVars,{v: repDict[v]},D)
              
      done = False   
    
    # print("outRep "+str(repDict))  
    # print("rest {}".format(eqs))
      
    # resubstitute the solution
    doneVars = set()
    while len(doneVars) < len(repDict):
      foundSome = False
      curVar = ""
      for v in repDict:
        if v in doneVars: continue
        # print("  rep try {}".format(repDict[v]))
        if (repDict[v].count("*") != 1) or (repDict[v].count("+") != 0): continue
        foundSome = True
        curVar = v; break
      if not(foundSome): break
      
      doneVars.add(curVar)
      val = int(repDict[curVar].split("*")[0])
      for v in repDict:
        if v == curVar: continue
        # print("  rep before: v={}, eq={}".format(v,repDict[v]))
        try: repDict[v] = symSetEqs([repDict[v]],allVars,{curVar: val},D)[0]
        except Exception: 
          # System if not solvable
          # print("Got you!")
          eqs = inEqs
          repDict = {}
          isValid = False
          return eqs,repDict,isValid
        # print("  rep after: v={}, eq={}".format(v,repDict[v]))
    
    # verify output
    isValid = symIsSol(eqs,repDict,D)
    # print("Verify with {}".format(isValid))
    return eqs,repDict,isValid


def symSolveTrimLUupper(U,b,D):
  """
  Solves Ux=b for given matrix U and vector b.

  Parameters
  ----------
  U : list
    Matrix as list of lists. Is in the Trimmed LU upper form.
  b : list
    Vector. Items are in the form '1*', '3*', ...
  D : int
    Integer that generates the corresponding FlipInts.

  Returns
  -------
  solDict : dict
    Solution in the form of a dictionary var:val
  outVec : list
    Solution in form of a vector.
  """
  assert len(b) == len(U), "Matrix has different size than vector with bIn={} and U={}".format(len(b),len(U))
  for i in range(len(U)):
    assert len(b) == len(U[i]), "Matrix-vector has different size than vector with bIn={} and U-vec.{}={}".format(len(b),i,len(U[i]))
  assert symIsTrimLUupper(U,D), "U does not have bespoke LU upper matrix form"
  # create a problem polynomial Vector (ppV)  
  s = len(b)
  assert (s % 2) == 1, "s is even with {}".format(s)
  xVars = [ "x%d"%i for i in range(s) ]
  xVec = [ "1*{}*".format(x) for x in xVars ]
  ppV = symMultMatVec(U,xVec,D,relaxed=True)
  for i in range(s):
    ppV[i] = symSubtractTerm(ppV[i], b[i], D)
  # housekeeping
  solDict = {}; outVec = []
  masterPPv = deepcopy(ppV)
  # solve row by row
  for i in reversed(range(s)):
    eqs = [ ppV[i] ]
    outEq,outDict,ok = symSolveLinSys(eqs,D)
    assert ok and outEq == [], "Wrong solution with ok={}, outEq={} and outDict={}".format(ok,outEq,outDict)
    solDict["x%d"%i] = outDict["x%d"%i]
    outVec.insert(0,solDict["x%d"%i])
    rep = { "x%d"%i: symPoly2int(solDict["x%d"%i],D) }
    ppV = symSetEqs(ppV,xVars,rep,D)
  # verify if we have a solution
  assert symIsSol(masterPPv, solDict, D), "Invalid solution for ppV={} and solDict={}".format(masterPPv,solDict)
  return solDict,outVec


